//! The `agent` command: the guide, the skill and the gate for coding agents
//! in one step.
//!
//! - The guide is a managed block in `AGENTS.md` (see [`guide`]).
//! - The skill is `skills/cargo-fallow/SKILL.md` of this repository, written
//!   to `.claude/skills/cargo-fallow/` for Claude Code and to
//!   `.agents/skills/cargo-fallow/` for Codex.
//! - The gate is the agent target of `hooks install`.
//!
//! The files go to the install root of `hooks install`.

pub mod guide;

use std::fmt::Write as _;
use std::path::PathBuf;

use clap::{Args, Subcommand, ValueEnum};
use fallow_report_protocol::exit_code::{EXIT_INVALID_INPUT, EXIT_OK};
use serde::Serialize;

use crate::cli::Format;
use crate::error::CliError;
use crate::hooks::files::{self, Outcome, ScriptState};
use crate::hooks::install::{self as hooks, FileOutcome, file_error};
use crate::hooks::settings::{self, Harness};
use crate::render;
use crate::report::TOOL_VERSION;
use crate::section::pretty;

/// The skill text, from `skills/cargo-fallow/SKILL.md`.
const SKILL: &str = include_str!("../../skills/cargo-fallow/SKILL.md");

/// The marker line of an installed skill. It goes after the front matter.
const SKILL_MARKER: &str = "<!-- Generated by cargo fallow agent install. -->";

/// A part that `agent install` writes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum Part {
    /// The managed block in `AGENTS.md`.
    Guide,
    /// The `cargo-fallow` skill.
    Skill,
    /// The gate before `git commit` and `git push`.
    Gate,
}

/// The subcommands of `agent`.
#[derive(Debug, Subcommand)]
pub enum Command {
    /// Install the guide in `AGENTS.md`, the `cargo-fallow` skill and the
    /// gate for Claude Code and Codex.
    Install(InstallArgs),
    /// Show the state of the guide, the skill and the gate.
    Status(StatusArgs),
    /// Remove the guide, the skill and the gate. A file that someone edited
    /// stays, unless you give `--force`.
    Uninstall(InstallArgs),
}

/// The flags of `agent install` and `agent uninstall`.
#[derive(Debug, Clone, Args)]
pub struct InstallArgs {
    /// Only this harness: `claude` (`.claude/`) or `codex` (`.codex/` and
    /// `.agents/skills/`). The default is each harness whose `.claude/` or
    /// `.codex/` folder exists, else Claude Code. `AGENTS.md` is shared.
    #[arg(long, value_enum, value_name = "HARNESS")]
    pub harness: Option<Harness>,
    /// Leave out these parts. The flag takes a list with commas and can
    /// repeat.
    #[arg(long, value_enum, value_name = "PART", value_delimiter = ',')]
    pub without: Vec<Part>,
    /// Path to the Cargo.toml of the workspace.
    #[arg(long, value_name = "PATH")]
    pub manifest_path: Option<PathBuf>,
    /// Show the changes, and write nothing.
    #[arg(long)]
    pub dry_run: bool,
    /// Replace or remove a file that someone edited.
    #[arg(long)]
    pub force: bool,
    /// The output format: `human` or `json`.
    #[arg(long, default_value = "human", value_parser = crate::cli::human_or_json())]
    pub format: Format,
}

impl InstallArgs {
    /// The defaults of `init --agents`.
    pub fn defaults(manifest_path: Option<PathBuf>, format: Format) -> Self {
        Self {
            harness: None,
            without: Vec::new(),
            manifest_path,
            dry_run: false,
            force: false,
            format,
        }
    }
}

/// The flags of `agent status`.
#[derive(Debug, Clone, Args)]
pub struct StatusArgs {
    /// Path to the Cargo.toml of the workspace.
    #[arg(long, value_name = "PATH")]
    pub manifest_path: Option<PathBuf>,
    /// The output format: `human` or `json`.
    #[arg(long, default_value = "human", value_parser = crate::cli::human_or_json())]
    pub format: Format,
}

impl Command {
    /// The output format.
    pub const fn format(&self) -> Format {
        match self {
            Self::Install(args) | Self::Uninstall(args) => args.format,
            Self::Status(args) => args.format,
        }
    }
}

/// The report of `agent install` and `agent uninstall`.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct AgentReport {
    /// The version of the document shape.
    pub schema_version: u32,
    /// Always `agent`.
    pub kind: &'static str,
    /// The version of cargo-fallow.
    pub version: &'static str,
    /// `install` or `uninstall`.
    pub action: &'static str,
    /// True when the command wrote nothing.
    pub dry_run: bool,
    /// Each file, in the order of the work.
    pub files: Vec<FileOutcome>,
}

/// The report of `agent status`.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct AgentStatus {
    /// The version of the document shape.
    pub schema_version: u32,
    /// Always `agent-status`.
    pub kind: &'static str,
    /// The version of cargo-fallow.
    pub version: &'static str,
    /// The state of the guide block in `AGENTS.md`.
    pub guide: GuideStatus,
    /// The state of the skill of each harness.
    pub skills: Vec<SkillStatus>,
    /// The state of each hook surface, the same as `hooks status`.
    pub gate: crate::hooks::install::HooksStatus,
}

/// The state of the guide block.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct GuideStatus {
    /// The path, relative to the install root.
    pub path: &'static str,
    /// `current`, `outdated`, `edited` or `absent`.
    pub state: &'static str,
}

/// The state of the skill of one harness.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct SkillStatus {
    /// `claude` or `codex`.
    pub harness: &'static str,
    /// The path, relative to the install root.
    pub path: String,
    /// `current`, `outdated`, `edited` or `absent`.
    pub state: &'static str,
}

/// The skill path of a harness, relative to the install root.
fn skill_path(harness: Harness) -> String {
    match harness {
        Harness::Claude => ".claude/skills/cargo-fallow/SKILL.md".to_owned(),
        Harness::Codex => ".agents/skills/cargo-fallow/SKILL.md".to_owned(),
    }
}

/// The installed skill text: the skill with the marker and the checksum
/// after the front matter.
fn skill_text() -> String {
    // A checkout with `core.autocrlf` can give the embedded file `\r\n` ends.
    let skill = SKILL.replace("\r\n", "\n");
    let marked = match skill.find("\n---\n") {
        Some(end) => {
            let (head, body) = skill.split_at(end + "\n---\n".len());
            format!("{head}{SKILL_MARKER}\n{body}")
        }
        None => format!("{SKILL_MARKER}\n{skill}"),
    };
    files::with_checksum(&marked, SKILL_MARKER)
}

/// Runs one `agent` subcommand and returns the exit code.
pub fn run(command: &Command) -> u8 {
    let result = match command {
        Command::Install(args) => install(args),
        Command::Uninstall(args) => uninstall(args),
        Command::Status(args) => status(args),
    };
    result.unwrap_or_else(|err| {
        err.emit(command.format());
        EXIT_INVALID_INPUT
    })
}

/// Runs `agent install`. A first pass writes nothing, so a refused file
/// stops the command before any change.
pub fn install(args: &InstallArgs) -> Result<u8, CliError> {
    refuse_empty(args)?;
    let checked = install_parts(args, true)?;
    let report = if args.dry_run {
        checked
    } else {
        install_parts(args, false)?
    };
    report.write(args.format)
}

/// Runs `agent uninstall`, with the same first pass as `install`.
pub fn uninstall(args: &InstallArgs) -> Result<u8, CliError> {
    refuse_empty(args)?;
    let checked = uninstall_parts(args, true)?;
    let report = if args.dry_run {
        checked
    } else {
        uninstall_parts(args, false)?
    };
    report.write(args.format)
}

/// `--without` must leave a part.
fn refuse_empty(args: &InstallArgs) -> Result<(), CliError> {
    if [Part::Guide, Part::Skill, Part::Gate]
        .iter()
        .all(|part| args.without.contains(part))
    {
        return Err(CliError::new(
            crate::error::ErrorCode::InvalidArgument,
            "`--without` leaves no part",
        )
        .with_help("Remove one part from `--without`: guide, skill or gate."));
    }
    Ok(())
}

/// Installs the parts. `dry_run` writes nothing.
fn install_parts(args: &InstallArgs, dry_run: bool) -> Result<AgentReport, CliError> {
    let root = hooks::install_root(args.manifest_path.as_deref())?;
    let harnesses = hooks::harnesses(&root.root, args.harness, false);
    let mut report = AgentReport::new("install", args.dry_run);
    if !args.without.contains(&Part::Guide) {
        let outcome = guide::install(&root.root, args.force, dry_run).map_err(file_error)?;
        report.push(&root.root, guide::FILE, outcome);
    }
    if !args.without.contains(&Part::Skill) {
        let text = skill_text();
        for &harness in &harnesses {
            let relative = skill_path(harness);
            let path = settings::safe_path(&root.root, &relative).map_err(file_error)?;
            let outcome = files::install_script(&path, &text, SKILL_MARKER, args.force, dry_run)
                .map_err(file_error)?;
            report.push(&root.root, &relative, outcome);
        }
    }
    if !args.without.contains(&Part::Gate) {
        report
            .files
            .extend(hooks::install_gate(&root, &harnesses, args.force, dry_run)?);
    }
    Ok(report)
}

/// Removes the parts. `dry_run` writes nothing.
fn uninstall_parts(args: &InstallArgs, dry_run: bool) -> Result<AgentReport, CliError> {
    let root = hooks::install_root(args.manifest_path.as_deref())?;
    let harnesses = match args.harness {
        Some(harness) => vec![harness],
        None => Harness::ALL.to_vec(),
    };
    let mut report = AgentReport::new("uninstall", args.dry_run);
    if !args.without.contains(&Part::Guide) {
        let outcome = guide::uninstall(&root.root, args.force, dry_run).map_err(file_error)?;
        report.push(&root.root, guide::FILE, outcome);
    }
    if !args.without.contains(&Part::Skill) {
        for &harness in &harnesses {
            let relative = skill_path(harness);
            let path = settings::safe_path(&root.root, &relative).map_err(file_error)?;
            let outcome = files::remove_script(&path, SKILL_MARKER, args.force, dry_run)
                .map_err(file_error)?;
            if outcome == Outcome::Removed
                && !dry_run
                && let Some(dir) = path.parent()
            {
                // The folder stays when it holds another file.
                let _ = std::fs::remove_dir(dir);
            }
            report.push(&root.root, &relative, outcome);
        }
    }
    if !args.without.contains(&Part::Gate) {
        let present: Vec<Harness> = harnesses
            .into_iter()
            .filter(|harness| root.root.join(harness.dir()).is_dir())
            .collect();
        report.files.extend(hooks::remove_gate(
            &root.root, &present, args.force, dry_run,
        )?);
    }
    Ok(report)
}

/// Runs `agent status`.
pub fn status(args: &StatusArgs) -> Result<u8, CliError> {
    let root = hooks::install_root(args.manifest_path.as_deref())?;
    let current = skill_text();
    let skills = Harness::ALL
        .into_iter()
        .map(|harness| {
            let path = skill_path(harness);
            let full = root.root.join(&path);
            let state = match files::script_state(&full, SKILL_MARKER) {
                Ok(ScriptState::Missing) | Err(_) => "absent",
                Ok(ScriptState::User) => "edited",
                Ok(ScriptState::Generated(_)) => {
                    if std::fs::read_to_string(&full).is_ok_and(|text| text == current) {
                        "current"
                    } else {
                        "outdated"
                    }
                }
            };
            SkillStatus {
                harness: harness.as_str(),
                path,
                state,
            }
        })
        .collect();
    let report = AgentStatus {
        schema_version: 1,
        kind: "agent-status",
        version: TOOL_VERSION,
        guide: GuideStatus {
            path: guide::FILE,
            state: guide::file_state(&root.root).as_str(),
        },
        skills,
        gate: crate::hooks::install::status_report(&root.root),
    };
    let text = if args.format == Format::Json {
        pretty(&report)?
    } else {
        report.human()
    };
    render::write_report(text.trim_end()).map_err(|err| CliError::output(&err))?;
    Ok(EXIT_OK)
}

impl AgentReport {
    const fn new(action: &'static str, dry_run: bool) -> Self {
        Self {
            schema_version: 1,
            kind: "agent",
            version: TOOL_VERSION,
            action,
            dry_run,
            files: Vec::new(),
        }
    }

    fn push(&mut self, root: &std::path::Path, relative: &str, outcome: Outcome) {
        self.files
            .push(FileOutcome::new(root, &root.join(relative), outcome));
    }

    fn write(&self, format: Format) -> Result<u8, CliError> {
        let text = if format == Format::Json {
            pretty(self)?
        } else {
            let mut text = String::new();
            for file in &self.files {
                let _ = writeln!(text, "{} {}", file.outcome.verb(self.dry_run), file.path);
            }
            if self.action == "install" && !self.dry_run {
                text.push_str("\nRun `cargo fallow agent status` to see the state.\n");
            }
            text
        };
        render::write_report(text.trim_end()).map_err(|err| CliError::output(&err))?;
        Ok(EXIT_OK)
    }
}

impl AgentStatus {
    fn human(&self) -> String {
        let mut text = format!("guide  {}: {}\n", self.guide.state, self.guide.path);
        for skill in &self.skills {
            let _ = writeln!(
                text,
                "skill  {} ({}): {}",
                skill.state, skill.harness, skill.path
            );
        }
        for surface in &self.gate.surfaces {
            let script = surface
                .script
                .as_deref()
                .map(|script| format!(": {script}"))
                .unwrap_or_default();
            let _ = writeln!(
                text,
                "gate   {} ({}){script}",
                surface.state, surface.surface
            );
        }
        text
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_installed_skill_keeps_its_front_matter_first() {
        let text = skill_text();
        assert!(text.starts_with("---\nname: cargo-fallow\n"), "{text}");
        assert_eq!(
            files::classify(&text, SKILL_MARKER),
            ScriptState::Generated(None)
        );
    }
}

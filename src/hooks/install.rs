//! `hooks install`, `hooks uninstall` and `hooks status`.
//!
//! The files go to the install root: the git top level of the workspace, else
//! the workspace root. When the workspace is below the git top level, the
//! scripts record the path of its manifest, so a session at the top level
//! still finds the workspace.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use fallow_report_protocol::exit_code::EXIT_OK;
use serde::Serialize;

use super::files::{self, Outcome, ScriptState};
use super::settings::{self, Harness};
use super::{InstallArgs, StatusArgs, Target};
use crate::cli::Format;
use crate::diff::git;
use crate::error::{CliError, ErrorCode};
use crate::render;
use crate::report::TOOL_VERSION;
use crate::section::pretty;

/// The marker line of each generated script.
pub const MARKER: &str = "# Generated by cargo fallow hooks install.";

/// The template of the agent gate script.
const GATE_TEMPLATE: &str = include_str!("gate.sh");

/// The placeholder of the installer version in the templates.
const VERSION_PLACEHOLDER: &str = "@@INSTALLER_VERSION@@";

/// The placeholder of the recorded manifest in the templates.
const MANIFEST_PLACEHOLDER: &str = "@@MANIFEST@@";

/// The name of the git hook.
const PRE_COMMIT: &str = "pre-commit";

/// The configuration files of hook managers that own the git hooks. The
/// command prints the step to add for them and writes nothing.
const HOOK_MANAGERS: [(&str, &str); 6] = [
    ("hk.pkl", "hk"),
    ("lefthook.yml", "lefthook"),
    ("lefthook.yaml", "lefthook"),
    (".lefthook.yml", "lefthook"),
    (".lefthook", "lefthook"),
    (".pre-commit-config.yaml", "pre-commit"),
];

/// The command that a hook manager runs. It blocks only on exit code 1, so
/// an error of the tool does not block the commit.
const MANAGER_COMMAND: &str = "sh -c 'RUSTUP_AUTO_INSTALL=0 cargo-fallow hooks gate-runtime pre-commit; s=$?; [ \"$s\" -ne 1 ] || exit 1'";

/// The report of `hooks install` and `hooks uninstall`.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct HooksReport {
    /// The version of the document shape.
    pub schema_version: u32,
    /// Always `hooks`.
    pub kind: &'static str,
    /// The version of cargo-fallow.
    pub version: &'static str,
    /// `install` or `uninstall`.
    pub action: &'static str,
    /// `agent` or `git`.
    pub target: &'static str,
    /// True when the command wrote nothing.
    pub dry_run: bool,
    /// Each file, in the order of the work.
    pub files: Vec<FileOutcome>,
    /// The step to add to a hook manager, when one owns the git hooks.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub manager_step: Option<ManagerStep>,
}

/// The outcome for one file.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct FileOutcome {
    /// The path, relative to the install root, with `/` separators. A path
    /// outside the root is absolute.
    pub path: String,
    /// What the command did.
    pub outcome: Outcome,
}

/// A hook manager that owns the git hooks.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct ManagerStep {
    /// The manager: `hk`, `lefthook`, `pre-commit` or `husky`.
    pub manager: &'static str,
    /// The command for the pre-commit step of the manager.
    pub command: &'static str,
}

/// The install root and the manifest to record in the scripts.
struct Root {
    root: PathBuf,
    /// The manifest of the workspace, relative to the root, when the
    /// workspace root is not the install root.
    manifest: String,
}

/// Finds the install root from the workspace of `manifest_path`.
fn install_root(manifest_path: Option<&Path>) -> Result<Root, CliError> {
    let workspace = crate::workspace::load(manifest_path, &["--offline".to_owned()])?;
    let workspace_root = workspace.root.as_std_path().to_path_buf();
    let top = git(&workspace_root, &["rev-parse", "--show-toplevel"])
        .ok()
        .map(|out| PathBuf::from(String::from_utf8_lossy(&out).trim()))
        .and_then(|top| top.canonicalize().ok());
    let workspace_root = workspace_root.canonicalize().unwrap_or(workspace_root);
    let Some(top) = top.filter(|top| workspace_root.starts_with(top)) else {
        return Ok(Root {
            root: workspace_root,
            manifest: String::new(),
        });
    };
    let manifest = workspace_root
        .strip_prefix(&top)
        .ok()
        .filter(|relative| !relative.as_os_str().is_empty())
        .map(|relative| format!("{}/Cargo.toml", slashed(relative)))
        .unwrap_or_default();
    Ok(Root {
        root: top,
        manifest,
    })
}

/// A relative path with `/` separators.
fn slashed(path: &Path) -> String {
    path.components()
        .map(|part| part.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

/// The display path of a file below the root.
fn display(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .map_or_else(|_| path.display().to_string(), slashed)
}

/// A shell word in single quotes. The path comes from the folder names of
/// the workspace, which can hold `$`, a backquote or a quote.
fn shell_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "'\\''"))
}

/// The agent gate script for a root.
fn gate_script(manifest: &str) -> String {
    files::with_checksum(
        &GATE_TEMPLATE
            .replace(VERSION_PLACEHOLDER, TOOL_VERSION)
            .replace(MANIFEST_PLACEHOLDER, &shell_quote(manifest)),
        MARKER,
    )
}

/// The git pre-commit hook for a root.
fn git_hook_script(manifest: &str) -> String {
    let manifest_line = if manifest.is_empty() {
        String::new()
    } else {
        format!(
            "CARGO_FALLOW_GATE_MANIFEST={}\nexport CARGO_FALLOW_GATE_MANIFEST\n",
            shell_quote(manifest)
        )
    };
    let script = format!(
        r#"#!/bin/sh
{MARKER}
# Installer version: {TOOL_VERSION}
# A git pre-commit hook. It blocks a commit when `cargo fallow check` finds a
# new finding in the changed files. A finding that HEAD already has does not
# block. An error of the tool does not block. Skip the hook for one commit
# with `git commit --no-verify`.
if ! command -v cargo-fallow >/dev/null 2>&1; then
  echo "cargo-fallow-gate: cargo-fallow not found, skipping the check." >&2
  exit 0
fi
{manifest_line}status=0
RUSTUP_AUTO_INSTALL=0 cargo-fallow hooks gate-runtime pre-commit || status=$?
if [ "$status" -eq 1 ]; then
  exit 1
fi
if [ "$status" -ne 0 ]; then
  echo "cargo-fallow-gate: the check stopped with exit code $status, skipping it." >&2
fi
exit 0
"#
    );
    files::with_checksum(&script, MARKER)
}

/// The harnesses of the agent target: the one of `--agent`, else each one
/// whose folder exists, else Claude Code. `installed` is true for uninstall,
/// which looks only at the harnesses with files.
fn harnesses(root: &Path, agent: Option<Harness>, installed: bool) -> Vec<Harness> {
    if let Some(agent) = agent {
        return vec![agent];
    }
    let present: Vec<Harness> = Harness::ALL
        .into_iter()
        .filter(|harness| root.join(harness.dir()).is_dir())
        .collect();
    if present.is_empty() && !installed {
        vec![Harness::Claude]
    } else {
        present
    }
}

fn file_error(message: String) -> CliError {
    CliError::new(ErrorCode::InvalidArgument, message)
}

/// Runs `hooks install`.
pub fn install(args: &InstallArgs) -> Result<u8, CliError> {
    refuse_agent_flag(args)?;
    let root = install_root(args.manifest_path.as_deref())?;
    let mut report = HooksReport::new("install", args);
    match args.target {
        Target::Agent => {
            let script = gate_script(&root.manifest);
            for harness in harnesses(&root.root, args.agent, false) {
                let script_path =
                    settings::safe_path(&root.root, &harness.script_path()).map_err(file_error)?;
                let outcome =
                    files::install_script(&script_path, &script, MARKER, args.force, args.dry_run)
                        .map_err(file_error)?;
                report.push(&root.root, &script_path, outcome);
                let settings_path = root.root.join(harness.settings_path());
                let outcome =
                    settings::install(&root.root, harness, args.dry_run).map_err(file_error)?;
                report.push(&root.root, &settings_path, outcome);
            }
        }
        Target::Git => {
            if let Some(path) = report.git_hook(&root.root)? {
                let outcome = files::install_script(
                    &path,
                    &git_hook_script(&root.manifest),
                    MARKER,
                    args.force,
                    args.dry_run,
                )
                .map_err(file_error)?;
                report.push(&root.root, &path, outcome);
            }
        }
    }
    report.write(args.format)
}

/// Runs `hooks uninstall`.
pub fn uninstall(args: &InstallArgs) -> Result<u8, CliError> {
    refuse_agent_flag(args)?;
    let root = install_root(args.manifest_path.as_deref())?;
    let mut report = HooksReport::new("uninstall", args);
    match args.target {
        Target::Agent => {
            for harness in harnesses(&root.root, args.agent, true) {
                let settings_path = root.root.join(harness.settings_path());
                let outcome =
                    settings::uninstall(&root.root, harness, args.dry_run).map_err(file_error)?;
                report.push(&root.root, &settings_path, outcome);
                let script_path =
                    settings::safe_path(&root.root, &harness.script_path()).map_err(file_error)?;
                let outcome = files::remove_script(&script_path, MARKER, args.force, args.dry_run)
                    .map_err(file_error)?;
                report.push(&root.root, &script_path, outcome);
                if outcome == Outcome::Removed && !args.dry_run {
                    // The folder stays when it holds another file.
                    let _ = std::fs::remove_dir(root.root.join(harness.dir()).join("hooks"));
                }
            }
        }
        Target::Git => {
            if let Some(path) = report.git_hook(&root.root)? {
                let outcome = files::remove_script(&path, MARKER, args.force, args.dry_run)
                    .map_err(file_error)?;
                report.push(&root.root, &path, outcome);
            }
        }
    }
    report.write(args.format)
}

/// `--agent` applies only to the agent target.
fn refuse_agent_flag(args: &InstallArgs) -> Result<(), CliError> {
    if args.target == Target::Git && args.agent.is_some() {
        return Err(CliError::new(
            ErrorCode::InvalidArgument,
            "`--agent` needs `--target agent`",
        )
        .with_help("Remove `--agent`, or use `--target agent`."));
    }
    Ok(())
}

/// The hook manager that owns the git hooks of the root, if any. Husky keeps
/// its hooks in `.husky/`, so the hook goes there and no step is needed.
fn manager(root: &Path) -> Option<ManagerStep> {
    HOOK_MANAGERS
        .iter()
        .find(|(file, _)| root.join(file).exists())
        .map(|&(_, manager)| ManagerStep {
            manager,
            command: MANAGER_COMMAND,
        })
}

/// The path of the pre-commit hook: `.husky/pre-commit` with husky, else the
/// hooks folder of git, which follows `core.hooksPath` and worktrees.
fn git_hook_path(root: &Path) -> Result<PathBuf, CliError> {
    if root.join(".husky").is_dir() {
        return Ok(root.join(".husky").join(PRE_COMMIT));
    }
    let out = git(root, &["rev-parse", "--git-path", "hooks"]).map_err(|detail| {
        CliError::new(
            ErrorCode::InvalidArgument,
            format!(
                "the workspace is not in a git repository ({})",
                detail.trim()
            ),
        )
        .with_help("Run `git init` first, or use `--target agent`.")
    })?;
    let hooks = PathBuf::from(String::from_utf8_lossy(&out).trim());
    let hooks = if hooks.is_absolute() {
        hooks
    } else {
        root.join(hooks)
    };
    Ok(hooks.join(PRE_COMMIT))
}

impl HooksReport {
    fn new(action: &'static str, args: &InstallArgs) -> Self {
        Self {
            schema_version: 1,
            kind: "hooks",
            version: TOOL_VERSION,
            action,
            target: match args.target {
                Target::Agent => "agent",
                Target::Git => "git",
            },
            dry_run: args.dry_run,
            files: Vec::new(),
            manager_step: None,
        }
    }

    /// The path of the git hook, or `None` when a hook manager owns the git
    /// hooks. The report then holds the step for the manager.
    fn git_hook(&mut self, root: &Path) -> Result<Option<PathBuf>, CliError> {
        if let Some(step) = manager(root) {
            self.manager_step = Some(step);
            return Ok(None);
        }
        git_hook_path(root).map(Some)
    }

    fn push(&mut self, root: &Path, path: &Path, outcome: Outcome) {
        self.files.push(FileOutcome {
            path: display(root, path),
            outcome,
        });
    }

    fn write(&self, format: Format) -> Result<u8, CliError> {
        let text = if format == Format::Json {
            pretty(self)?
        } else {
            self.human()
        };
        render::write_report(text.trim_end()).map_err(|err| CliError::output(&err))?;
        Ok(EXIT_OK)
    }

    fn human(&self) -> String {
        let mut text = String::new();
        for file in &self.files {
            let _ = writeln!(text, "{} {}", file.outcome.verb(self.dry_run), file.path);
        }
        if let Some(step) = &self.manager_step {
            let _ = writeln!(
                text,
                "{} runs the git hooks of this repository. Add this command to its pre-commit hook:\n\n  {}",
                step.manager, step.command
            );
        } else if self.action == "install" && !self.dry_run {
            text.push_str(match self.target {
                "agent" => "\nThe gate blocks a `git commit` or `git push` of the agent when `cargo fallow check` finds a new finding in the changed files.\n",
                _ => "\nThe hook blocks a commit when `cargo fallow check` finds a new finding in the changed files. Skip it for one commit with `git commit --no-verify`.\n",
            });
        }
        text
    }
}

/// The report of `hooks status`.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct HooksStatus {
    /// The version of the document shape.
    pub schema_version: u32,
    /// Always `hooks-status`.
    pub kind: &'static str,
    /// The version of cargo-fallow.
    pub version: &'static str,
    /// The state of each surface: `claude`, `codex` and `git`.
    pub surfaces: Vec<SurfaceStatus>,
}

/// The state of one hook surface.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct SurfaceStatus {
    /// `claude`, `codex` or `git`.
    pub surface: &'static str,
    /// `installed`, `partial`, `edited`, `managed` or `absent`. `partial`
    /// means that the handler or the script is missing. `edited` means that
    /// the script is not the generated one. `managed` means that a hook
    /// manager runs the git hooks.
    pub state: &'static str,
    /// The script, relative to the install root.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub script: Option<String>,
    /// The cargo-fallow version that wrote the script.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub installer_version: Option<String>,
}

/// Runs `hooks status`.
pub fn status(args: &StatusArgs) -> Result<u8, CliError> {
    let root = install_root(args.manifest_path.as_deref())?;
    let report = status_report(&root.root);
    let text = if args.format == Format::Json {
        pretty(&report)?
    } else {
        report
            .surfaces
            .iter()
            .fold(String::new(), |mut text, surface| {
                let version = surface
                    .installer_version
                    .as_deref()
                    .map(|version| format!(" (cargo-fallow {version})"))
                    .unwrap_or_default();
                let script = surface
                    .script
                    .as_deref()
                    .map(|script| format!(": {script}"))
                    .unwrap_or_default();
                let _ = writeln!(
                    text,
                    "{:<7}{}{script}{version}",
                    surface.surface, surface.state
                );
                text
            })
    };
    render::write_report(text.trim_end()).map_err(|err| CliError::output(&err))?;
    Ok(EXIT_OK)
}

/// The state of each surface in a root.
pub fn status_report(root: &Path) -> HooksStatus {
    let mut surfaces = Vec::new();
    for harness in Harness::ALL {
        let script = harness.script_path();
        let state = files::script_state(&root.join(&script), MARKER).ok();
        let handler = settings::has_handler(root, harness);
        surfaces.push(surface(harness.as_str(), state, handler, script));
    }
    if manager(root).is_some() {
        surfaces.push(SurfaceStatus {
            surface: "git",
            state: "managed",
            script: None,
            installer_version: None,
        });
    } else if let Ok(path) = git_hook_path(root) {
        let state = files::script_state(&path, MARKER).ok();
        let exists = !matches!(state, Some(ScriptState::Missing) | None);
        surfaces.push(surface("git", state, exists, display(root, &path)));
    }
    HooksStatus {
        schema_version: 1,
        kind: "hooks-status",
        version: TOOL_VERSION,
        surfaces,
    }
}

fn surface(
    name: &'static str,
    state: Option<ScriptState>,
    handler: bool,
    script: String,
) -> SurfaceStatus {
    let (state, installer_version) = match (state, handler) {
        (Some(ScriptState::Generated(version)), true) => ("installed", version),
        (Some(ScriptState::User), _) => ("edited", None),
        (Some(ScriptState::Missing) | None, false) => ("absent", None),
        (_, _) => ("partial", None),
    };
    SurfaceStatus {
        surface: name,
        state,
        script: (state != "absent").then_some(script),
        installer_version,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_manifest_path_cannot_inject_shell_code() {
        assert_eq!(shell_quote("a'b"), "'a'\\''b'");
        let hostile = "p$(touch x)`id`\"'/Cargo.toml";
        for script in [gate_script(hostile), git_hook_script(hostile)] {
            assert!(script.contains(&shell_quote(hostile)), "{script}");
        }
    }

    #[test]
    fn generated_scripts_have_a_valid_checksum_and_no_placeholder() {
        for script in [gate_script("rust/Cargo.toml"), git_hook_script("")] {
            assert_eq!(
                files::classify(&script, MARKER),
                ScriptState::Generated(Some(TOOL_VERSION.to_owned()))
            );
            assert!(!script.contains("@@"), "{script}");
        }
    }
}

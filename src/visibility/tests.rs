//! Tests of the analysis order on a real module graph.

use std::fmt::Debug;
use std::fmt::Write as _;
use std::fs;

use super::*;
use crate::graph::{self, Production};

fn ok<T, E: Debug>(result: Result<T, E>, what: &str) -> T {
    match result {
        Ok(value) => value,
        Err(err) => panic!("{what}: {err:?}"),
    }
}

/// The findings of a `--precise` run on a library with a public re-export
/// of `hand::Thing` in `proto.rs`, after `--precise` mode decides that `Thing`
/// can be `pub(crate)`.
fn precise_findings(proto_header: &str) -> Vec<String> {
    let dir = ok(tempfile::tempdir(), "a temporary directory");
    let root = dir.path();
    ok(fs::create_dir_all(root.join("src")), "the src folder");
    let files = [
        (
            "Cargo.toml",
            "[package]\nname = \"lib1\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n[workspace]\n",
        ),
        ("src/lib.rs", "mod hand;\npub mod proto;\n"),
        ("src/hand.rs", "pub struct Thing;\n"),
    ];
    for (path, text) in files {
        ok(fs::write(root.join(path), text), "write a file");
    }
    let proto = format!("{proto_header}pub use crate::hand::Thing;\n");
    ok(
        fs::write(root.join("src/proto.rs"), proto),
        "write the re-export",
    );
    let workspace = ok(
        crate::workspace::load(Some(&root.join("Cargo.toml")), &[]),
        "the workspace",
    );
    let module_graph = graph::build(&workspace, &Production { bins: Vec::new() });
    let options = Options {
        exclude: Vec::new(),
        public: None,
        uniform_fields: false,
        root: root.to_path_buf(),
    };
    let mut analysis = analyze(&module_graph, &options);
    let Some(thing) = module_graph
        .items
        .iter()
        .position(|item| item.name == "Thing" && item.kind != ItemKind::Use)
    else {
        panic!("the graph has no Thing item");
    };
    analysis.findings.push(Finding {
        kind: FindingKind::UnnecessaryPublic,
        item: thing,
        test_only: false,
    });
    refine(&module_graph, &options, &mut analysis);
    skip_generated(&module_graph, &mut analysis);
    analysis
        .findings
        .iter()
        .map(|finding| {
            let item = &module_graph.items[finding.item];
            format!("{:?} {} {}", finding.kind, item.file, item.name)
        })
        .collect()
}

#[test]
fn a_reexport_in_a_generated_file_still_holds_back_its_target() {
    let plain = precise_findings("");
    assert!(
        !plain.iter().any(|row| row.ends_with("src/hand.rs Thing")),
        "{plain:?}"
    );
    assert!(
        plain.iter().any(|row| row.contains("src/proto.rs")),
        "{plain:?}"
    );
    let generated = precise_findings("// @generated by a code generator\n");
    assert!(
        !generated
            .iter()
            .any(|row| row.ends_with("src/hand.rs Thing")),
        "{generated:?}"
    );
    assert!(
        !generated.iter().any(|row| row.contains("src/proto.rs")),
        "{generated:?}"
    );
}

#[test]
fn a_public_crate_pattern_matches_with_globs() {
    assert!(super::name_matches("base", "base"));
    assert!(super::name_matches("bas*", "base"));
    assert!(super::name_matches("*-api", "fallow-api"));
    assert!(super::name_matches("f*l*w", "fallow"));
    assert!(super::name_matches("*", "anything"));
    assert!(!super::name_matches("base", "based"));
    assert!(!super::name_matches("a*a", "a"));
    assert!(super::name_matches("a*b*c", "a-x-b-y-c"));
    assert!(!super::name_matches("xy*yx", "xyx"));
    assert!(super::name_matches("**", ""));
    assert!(!super::name_matches("", "a"));
}

/// Each field access `.a` can name each field `a`. The credits keep one site
/// for each access and one group for the name, so their size grows with the
/// accesses and the fields, not with their product.
#[test]
fn name_credits_grow_with_the_sites_and_the_items() {
    const COUNT: usize = 400;
    let dir = ok(tempfile::tempdir(), "a temporary directory");
    let root = dir.path();
    ok(fs::create_dir_all(root.join("src")), "the src folder");
    ok(
        fs::write(
            root.join("Cargo.toml"),
            "[package]\nname = \"big\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n[workspace]\n",
        ),
        "write the manifest",
    );
    let mut source = String::new();
    for index in 0..COUNT {
        let _ = writeln!(
            source,
            "pub struct S{index} {{ pub a: u32 }}\nimpl S{index} {{ fn g(&self) -> u32 {{ self.a }} }}"
        );
    }
    ok(
        fs::write(root.join("src/lib.rs"), source),
        "write the source",
    );
    let workspace = ok(
        crate::workspace::load(Some(&root.join("Cargo.toml")), &[]),
        "the workspace",
    );
    let module_graph = graph::build(&workspace, &Production { bins: Vec::new() });
    let credits = Resolver::new(&module_graph).credits();
    let stored = credits.direct.len()
        + credits.sites.len()
        + credits.groups.iter().map(Vec::len).sum::<usize>();
    assert!(
        stored < COUNT * 20,
        "{stored} stored credits for {COUNT} fields"
    );
    let field = module_graph
        .items
        .iter()
        .position(|item| item.kind == ItemKind::Field)
        .unwrap_or_default();
    assert_eq!(
        credits
            .for_item(field)
            .iter()
            .filter(|credit| credit.class == Class::Untyped)
            .count(),
        COUNT,
        "each access names the field"
    );
}
